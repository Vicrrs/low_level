#include <iostream>
using namespace std;

int main() {

	double base, altura, area;

	cout << "Digite a base do retangulo: " << endl;
	cin >> base;

	cout << "Digite a altura do retangulo: " << endl;
	cin >> altura;

	area = base * altura;

	cout << "A area do retangulo é: " << area << endl;

	return 0;

}

